public class Operations {
    public static void main(String[] args) {
        int a = 10;
        int b = 5;
        double x = 4.0;
        System.out.println(a + b);
        System.out.println(a - b);
        System.out.println(a * b);
        System.out.println(a / b);
        System.out.println(a % b);
        System.out.println(x / b);
        System.out.println(a + b * 2);
        System.out.println((a + b) * 2);
        System.out.println(b / x);
        System.out.println(3+4);
        System.out.println("3" + "92");

    }
}